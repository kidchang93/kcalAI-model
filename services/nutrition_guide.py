_GUIDES: dict[str, ConditionGuide] = {
    guide.condition: guide for guide in (_CKD, _HYPERTENSION, _DIABETES)
}


def get_guide(condition: str) -> ConditionGuide | None:
    """질환 코드 → 가이드. 근거 문서가 없는 질환(pregnancy·cancer)은 None."""
    return _GUIDES.get(condition)


def available_conditions() -> tuple[str, ...]:
    """가이드가 있는 질환 코드. 앱이 '가이드 보기' 진입점을 그릴지 판단하는 데 쓴다."""
    return tuple(_GUIDES)
