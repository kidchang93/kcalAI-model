"""질환별 식이 가이드 — 우리가 이미 가진 근거를 사용자 언어로 꺼낸다.

`docs/CARE_LOOP.md` §5. **새 의학 조사가 아니다.** 문장의 출처는 전부 다음 두 문서이고,
그 문서들이 학회 지침 원문을 이미 인용해 두었다:

- `docs/CKD_NUTRITION.md` (대한신장학회 KSN1·KSN2)
- `docs/CHRONIC_NUTRITION_SOURCES.md` (KSH2026 고혈압 · KDA2025 당뇨 · KDRI2025)

**왜 서버가 갖는가** (CARE_LOOP §5-3): ① 지침이 개정되면 앱 심사 없이 고칠 수 있어야 하고
② 판정 규칙(`ckd_food_rules`·`chronic_food_rules`)과 같은 저장소에서 함께 고쳐야 설명과 판정이
어긋나지 않으며 ③ 경고 응답의 `basis` 와 같은 출처를 가리켜야 한다.

## 쓰면서 지킨 것 (`CHRONIC_NUTRITION_SOURCES.md` §6 노출 원칙)

- **사실 서술이지 지시가 아니다.** "드세요"가 아니라 "지침은 ~를 권합니다"로 쓴다.
- **개인 목표량을 계산해 주지 않는다.** 병기별로 값이 갈리면 **양쪽을 병기**하고 어느 쪽인지는
  사용자·의료진이 정한다. 그래서 이 모듈은 사용자 프로필을 읽지 않는다.
- **출처 없는 문장을 쓰지 않는다.** 모든 축에 `sources` 가 붙는다.
- **근거 문서가 없는 질환은 만들지 않는다.** `pregnancy`·`cancer` 는 조사한 적이 없어 비운다 —
  빈 것이 지어낸 것보다 낫다.
"""

from dataclasses import dataclass, field


@dataclass(frozen=True)
class GuideSection:
    title: str
    paragraphs: tuple[str, ...]


@dataclass(frozen=True)
class GuideAxis:
    axis: str
    label: str
    # 한 줄 요약. 목록·진입 카드에서 쓴다.
    summary: str
    sections: tuple[GuideSection, ...]
    sources: tuple[str, ...]
    # 이 축에만 붙는 주의. 병존 충돌처럼 축 단위로 갈리는 경고를 담는다.
    caution: str | None = None


@dataclass(frozen=True)
class ConditionGuide:
    condition: str
    label: str
    intro: str
    axes: tuple[GuideAxis, ...] = field(default_factory=tuple)


